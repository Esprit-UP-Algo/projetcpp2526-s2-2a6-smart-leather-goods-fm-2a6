-- Procédure: Enregistrer ravitaillement
CREATE OR REPLACE PROCEDURE SP_LOG_RAVITAILLEMENT(
    p_matiere IN VARCHAR2,
    p_fournisseur IN VARCHAR2,
    p_score IN NUMBER,
    p_quantite IN NUMBER,
    p_budget IN NUMBER,
    p_risque IN NUMBER,
    p_couverture IN NUMBER,
    p_strategie IN VARCHAR2
) AS
    v_log_id VARCHAR2(40);
BEGIN
    v_log_id := 'RAV-' || TO_CHAR(SYSDATE, 'YYYYMMDD-HH24MISS');
    
    INSERT INTO RAVITAILLEMENT_LOG (
        LOG_ID, MATIERE, FOURNISSEUR, SCORE_GLOBAL, QUANTITE_COMMANDE,
        BUDGET_ESTIME, RISQUE, COUVERTURE_JOURS, STRATEGIE
    ) VALUES (
        v_log_id, p_matiere, p_fournisseur, p_score, p_quantite,
        p_budget, p_risque, p_couverture, p_strategie
    );
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('✓ Ravitaillement enregistré: ' || v_log_id);
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('✗ Erreur: ' || SQLERRM);
        RAISE;
END;
/

-- Procédure: Calculer besoin ravitaillement
CREATE OR REPLACE PROCEDURE SP_CALCULER_BESOIN(
    p_categorie IN VARCHAR2,
    p_stock_actuel IN NUMBER,
    p_seuil_securite IN NUMBER,
    p_conso_prevue IN NUMBER,
    p_besoin OUT NUMBER,
    p_couverture OUT NUMBER
) AS
BEGIN
    p_besoin := GREATEST(0, p_seuil_securite + p_conso_prevue - p_stock_actuel);
    p_couverture := p_stock_actuel / GREATEST(0.01, p_conso_prevue / 7.0);
    
    DBMS_OUTPUT.PUT_LINE('Catégorie: ' || p_categorie);
    DBMS_OUTPUT.PUT_LINE('Besoin calculé: ' || TO_CHAR(p_besoin, '999999.99') || ' M²');
    DBMS_OUTPUT.PUT_LINE('Couverture: ' || TO_CHAR(p_couverture, '999.99') || ' jours');
END;
