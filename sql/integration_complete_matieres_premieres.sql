-- Vue agrégée du stock
CREATE OR REPLACE VIEW V_STOCK_AGREGE AS
SELECT 
    CATEGORIE_MP,
    SUM(QUANTITE) AS QUANTITE_TOTALE,
    COUNT(*) AS NB_LOTS,
    MAX(DATE_MODIFICATION) AS DERNIERE_MAJ,
    AVG(QUANTITE) AS QUANTITE_MOYENNE
FROM MATIERES_PREMIERES
GROUP BY CATEGORIE_MP;

-- Vue fournisseurs actifs
CREATE OR REPLACE VIEW V_FOURNISSEURS_ACTIFS AS
SELECT 
    ID_FOURNISSEUR,
    NOM_FOURNISSEUR,
    TYPE_CUIR,
    PRIX_PAR_M2,
    QUALITE,
    DELAI_JOURS,
    STOCK_DISPO,
    EMAIL,
    TELEPHONE
FROM FOURNISSEURS
WHERE ACTIF = '1'
ORDER BY TYPE_CUIR, PRIX_PAR_M2;

-- Vue analyse ravitaillement
CREATE OR REPLACE VIEW V_ANALYSE_RAVITAILLEMENT AS
SELECT 
    TO_CHAR(DATE_LOG, 'YYYY-MM') AS MOIS,
    MATIERE,
    COUNT(*) AS NB_COMMANDES,
    SUM(QUANTITE_COMMANDE) AS QTE_TOTALE,
    SUM(BUDGET_ESTIME) AS BUDGET_TOTAL,
    AVG(SCORE_GLOBAL) AS SCORE_MOYEN,
    AVG(COUVERTURE_JOURS) AS COUVERTURE_MOYENNE
FROM RAVITAILLEMENT_LOG
GROUP BY TO_CHAR(DATE_LOG, 'YYYY-MM'), MATIERE
ORDER BY MOIS DESC, MATIERE;

